"""Reference motions for imitation: a root trajectory plus robot joint angles at a fixed frame rate.

A `Motion` stores, per frame,

* the free-floating root body's world position and orientation (wxyz quaternion),
* the angle of every 1-DOF robot joint, by joint name,
* optionally the world positions of named key bodies (hands, feet, knees, ...),

and is saved as a small .npz (arrays + a JSON header, no pickle). It can be sampled at any time with
linear interpolation (spherical for the root orientation), looped, and differentiated by finite
differences. A looping motion stores one cycle of N frames plus the planar rigid transform C that maps
frame 0 onto "frame N" (the first frame of the next cycle): a walking cycle advances and turns the root
by C every period, so the clip repeats forever without the root jumping back (as in DeepMimic, Peng et
al. 2018, which offsets the root of cyclic clips by the cycle's displacement).

Conventions: Z up, the robot faces +X at yaw 0, SI units and radians, quaternions w-first like MuJoCo.
Joint values are matched to a model by joint name, so a motion recorded on one body plays on another
generated by the same parametric model.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

import mujoco
import numpy as np

MOTION_FORMAT = "simulatics-motion"


# =========================================================================================================
# Quaternion / rotation helpers (batched over leading axes, wxyz)
# =========================================================================================================
def quat_normalize(q: np.ndarray) -> np.ndarray:
    q = np.asarray(q, float)
    return q / np.linalg.norm(q, axis=-1, keepdims=True)


def quat_mul(p: np.ndarray, q: np.ndarray) -> np.ndarray:
    """Hamilton product p * q (broadcasting over leading axes)."""
    p, q = np.asarray(p, float), np.asarray(q, float)
    w1, x1, y1, z1 = np.moveaxis(p, -1, 0)
    w2, x2, y2, z2 = np.moveaxis(q, -1, 0)
    return np.stack([w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2,
                     w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
                     w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2,
                     w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2], axis=-1)


def quat_conj(q: np.ndarray) -> np.ndarray:
    q = np.asarray(q, float)
    return q * np.array([1.0, -1.0, -1.0, -1.0])


def quat_to_mat(q: np.ndarray) -> np.ndarray:
    """(..., 4) -> (..., 3, 3) rotation matrices (body -> world)."""
    q = quat_normalize(q)
    w, x, y, z = np.moveaxis(q, -1, 0)
    return np.stack([
        np.stack([1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)], axis=-1),
        np.stack([2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)], axis=-1),
        np.stack([2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)], axis=-1),
    ], axis=-2)


def mat_to_quat(R: np.ndarray) -> np.ndarray:
    """(..., 3, 3) rotation matrices -> (..., 4) unit quaternions with w >= 0 (Shepperd's method)."""
    R = np.asarray(R, float)
    shape = R.shape[:-2]
    m = R.reshape(-1, 3, 3)
    tr = m[:, 0, 0] + m[:, 1, 1] + m[:, 2, 2]
    cand = np.stack([tr, m[:, 0, 0], m[:, 1, 1], m[:, 2, 2]], axis=1)
    k = np.argmax(cand, axis=1)
    q = np.zeros((len(m), 4))
    for case in range(4):
        i = np.flatnonzero(k == case)
        if i.size == 0:
            continue
        a = m[i]
        if case == 0:
            s = 2.0 * np.sqrt(np.maximum(1.0 + tr[i], 1e-12))
            q[i] = np.stack([0.25 * s, (a[:, 2, 1] - a[:, 1, 2]) / s, (a[:, 0, 2] - a[:, 2, 0]) / s,
                             (a[:, 1, 0] - a[:, 0, 1]) / s], axis=1)
        elif case == 1:
            s = 2.0 * np.sqrt(np.maximum(1.0 + a[:, 0, 0] - a[:, 1, 1] - a[:, 2, 2], 1e-12))
            q[i] = np.stack([(a[:, 2, 1] - a[:, 1, 2]) / s, 0.25 * s, (a[:, 0, 1] + a[:, 1, 0]) / s,
                             (a[:, 0, 2] + a[:, 2, 0]) / s], axis=1)
        elif case == 2:
            s = 2.0 * np.sqrt(np.maximum(1.0 + a[:, 1, 1] - a[:, 0, 0] - a[:, 2, 2], 1e-12))
            q[i] = np.stack([(a[:, 0, 2] - a[:, 2, 0]) / s, (a[:, 0, 1] + a[:, 1, 0]) / s, 0.25 * s,
                             (a[:, 1, 2] + a[:, 2, 1]) / s], axis=1)
        else:
            s = 2.0 * np.sqrt(np.maximum(1.0 + a[:, 2, 2] - a[:, 0, 0] - a[:, 1, 1], 1e-12))
            q[i] = np.stack([(a[:, 1, 0] - a[:, 0, 1]) / s, (a[:, 0, 2] + a[:, 2, 0]) / s,
                             (a[:, 1, 2] + a[:, 2, 1]) / s, 0.25 * s], axis=1)
    q *= np.where(q[:, :1] < 0, -1.0, 1.0)
    return quat_normalize(q).reshape(*shape, 4)


def quat_to_rotvec(q: np.ndarray) -> np.ndarray:
    """(..., 4) -> rotation vectors (axis * angle, angle in [0, pi])."""
    q = quat_normalize(q)
    q = q * np.where(q[..., :1] < 0, -1.0, 1.0)
    v = q[..., 1:]
    s = np.linalg.norm(v, axis=-1, keepdims=True)
    ang = 2.0 * np.arctan2(s, q[..., :1])
    scale = np.where(s > 1e-12, ang / np.maximum(s, 1e-12), 2.0)
    return v * scale


def rotvec_to_quat(v: np.ndarray) -> np.ndarray:
    v = np.asarray(v, float)
    ang = np.linalg.norm(v, axis=-1, keepdims=True)
    half = 0.5 * ang
    s = np.where(ang > 1e-12, np.sin(half) / np.maximum(ang, 1e-12), 0.5)
    return np.concatenate([np.cos(half), v * s], axis=-1)


def mat_to_rotvec(R: np.ndarray) -> np.ndarray:
    return quat_to_rotvec(mat_to_quat(R))


def quat_slerp(q0: np.ndarray, q1: np.ndarray, t) -> np.ndarray:
    """Spherical interpolation, shortest arc, batched (t broadcasts over leading axes)."""
    q0, q1 = quat_normalize(q0), quat_normalize(q1)
    t = np.asarray(t, float)[..., None]
    d = np.sum(q0 * q1, axis=-1, keepdims=True)
    q1 = np.where(d < 0, -q1, q1)
    d = np.abs(d)
    theta = np.arccos(np.clip(d, -1.0, 1.0))
    s = np.sin(theta)
    small = s < 1e-6
    w0 = np.where(small, 1.0 - t, np.sin((1.0 - t) * theta) / np.where(small, 1.0, s))
    w1 = np.where(small, t, np.sin(t * theta) / np.where(small, 1.0, s))
    return quat_normalize(w0 * q0 + w1 * q1)


def quat_continuous(q: np.ndarray) -> np.ndarray:
    """Flip signs along axis 0 so consecutive quaternions are in the same hemisphere."""
    q = np.array(q, float)
    for i in range(1, len(q)):
        if float(np.dot(q[i], q[i - 1])) < 0:
            q[i] = -q[i]
    return q


def yaw_quat(yaw) -> np.ndarray:
    yaw = np.asarray(yaw, float)
    z = np.zeros_like(yaw)
    return np.stack([np.cos(yaw / 2), z, z, np.sin(yaw / 2)], axis=-1)


def rot_z(yaw) -> np.ndarray:
    """(...) yaw angles -> (..., 3, 3)."""
    yaw = np.asarray(yaw, float)
    c, s = np.cos(yaw), np.sin(yaw)
    z, o = np.zeros_like(yaw), np.ones_like(yaw)
    return np.stack([np.stack([c, -s, z], -1), np.stack([s, c, z], -1), np.stack([z, z, o], -1)], -2)


def yaw_of_mat(R: np.ndarray) -> np.ndarray:
    R = np.asarray(R, float)
    return np.arctan2(R[..., 1, 0], R[..., 0, 0])


def yaw_of_quat(q: np.ndarray) -> np.ndarray:
    q = quat_normalize(q)
    w, x, y, z = np.moveaxis(q, -1, 0)
    return np.arctan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))


def wrap_angle(a):
    return (np.asarray(a, float) + np.pi) % (2 * np.pi) - np.pi


# =========================================================================================================
# Planar rigid transforms (yaw about z + xy translation): cycle offsets and re-anchoring
# =========================================================================================================
def planar_compose(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Transform a o b (apply b first). Each is (..., 3) = (tx, ty, yaw): x' = Rz(yaw) x + t."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    c, s = np.cos(a[..., 2]), np.sin(a[..., 2])
    tx = a[..., 0] + c * b[..., 0] - s * b[..., 1]
    ty = a[..., 1] + s * b[..., 0] + c * b[..., 1]
    return np.stack([tx, ty, a[..., 2] + b[..., 2]], axis=-1)


def planar_apply_points(T: np.ndarray, p: np.ndarray) -> np.ndarray:
    """Apply (..., 3) planar transforms to points (..., [K,] 3); z is unchanged."""
    T, p = np.asarray(T, float), np.asarray(p, float)
    extra = p.ndim - T.ndim
    Tb = T.reshape(T.shape[:-1] + (1,) * extra + (3,))
    c, s = np.cos(Tb[..., 2]), np.sin(Tb[..., 2])
    x = c * p[..., 0] - s * p[..., 1] + Tb[..., 0]
    y = s * p[..., 0] + c * p[..., 1] + Tb[..., 1]
    return np.stack([x, y, p[..., 2]], axis=-1)


def planar_apply_vectors(T: np.ndarray, v: np.ndarray) -> np.ndarray:
    """Rotate free vectors (..., [K,] 3) by the yaw of (..., 3) planar transforms."""
    T = np.asarray(T, float)
    return planar_apply_points(np.concatenate([np.zeros(T.shape[:-1] + (2,)), T[..., 2:3]], axis=-1), v)


def planar_apply_quats(T: np.ndarray, q: np.ndarray) -> np.ndarray:
    return quat_mul(yaw_quat(np.asarray(T, float)[..., 2]), q)


def heading_pose(root_pos: np.ndarray, root_quat: np.ndarray) -> np.ndarray:
    """(x, y, yaw) of root poses: the planar 'heading frame'."""
    return np.concatenate([np.asarray(root_pos, float)[..., :2], yaw_of_quat(root_quat)[..., None]], axis=-1)


def planar_between(src: np.ndarray, dst: np.ndarray) -> np.ndarray:
    """Planar transform T with T(src frame) = dst frame (both (x, y, yaw))."""
    src, dst = np.asarray(src, float), np.asarray(dst, float)
    dyaw = dst[..., 2] - src[..., 2]
    c, s = np.cos(dyaw), np.sin(dyaw)
    tx = dst[..., 0] - (c * src[..., 0] - s * src[..., 1])
    ty = dst[..., 1] - (s * src[..., 0] + c * src[..., 1])
    return np.stack([tx, ty, dyaw], axis=-1)


