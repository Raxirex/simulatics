def one_dof_joints(model: mujoco.MjModel) -> list[str]:
    """Names of the model's hinge and slide joints, in model order."""
    out = []
    for j in range(model.njnt):
        if model.jnt_type[j] in (mujoco.mjtJoint.mjJNT_HINGE, mujoco.mjtJoint.mjJNT_SLIDE):
            out.append(model.joint(j).name)
    return out


def free_root(model: mujoco.MjModel) -> tuple[int, int, int]:
    """(body, qpos address, dof address) of the model's first free joint; ValueError if there is none."""
    for j in range(model.njnt):
        if model.jnt_type[j] == mujoco.mjtJoint.mjJNT_FREE:
            return int(model.jnt_bodyid[j]), int(model.jnt_qposadr[j]), int(model.jnt_dofadr[j])
    raise ValueError("motion imitation needs a model with a free-floating root joint")


def _body(model: mujoco.MjModel, name: str) -> int:
    return mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, name)


def robot_keypoints(model: mujoco.MjModel) -> dict[str, tuple[int, np.ndarray]]:
    """Named key points of the built-in humanoid as (body id, point in the body frame), read from the model.

    pelvis = midpoint of the two hip joints; torso = midpoint of the shoulder joints (top of the torso
    without arms); head = centre of the head geom; <side>_hip / knee / foot = hip, knee and ankle joint
    centres; <side>_shoulder / elbow / hand = shoulder, elbow and wrist joint centres (end of the forearm
    when the robot has no hands). Points whose bodies are missing are left out, so other robots get a
    subset (at least the root as "pelvis").
    """
    kp: dict[str, tuple[int, np.ndarray]] = {}
    root, _, _ = free_root(model)
    thighs = [_body(model, f"{s}_thigh") for s in ("left", "right")]
    pel = _body(model, "pelvis")
    if pel >= 0 and min(thighs) >= 0 and all(model.body_parentid[t] == pel for t in thighs):
        kp["pelvis"] = (pel, (model.body_pos[thighs[0]] + model.body_pos[thighs[1]]) / 2)
    else:
        kp["pelvis"] = (root, np.zeros(3))
    arms = [_body(model, f"{s}_upper_arm") for s in ("left", "right")]
    if min(arms) >= 0 and model.body_parentid[arms[0]] == model.body_parentid[arms[1]]:
        kp["torso"] = (int(model.body_parentid[arms[0]]), (model.body_pos[arms[0]] + model.body_pos[arms[1]]) / 2)
    head = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_GEOM, "head")
    if head >= 0:
        kp["head"] = (int(model.geom_bodyid[head]), model.geom_pos[head].copy())
    for s in ("left", "right"):
        for key, body in (("hip", "thigh"), ("knee", "shin"), ("foot", "foot"), ("shoulder", "upper_arm"),
                          ("elbow", "forearm")):
            b = _body(model, f"{s}_{body}")
            if b >= 0:
                kp[f"{s}_{key}"] = (b, np.zeros(3))
        hb = _body(model, f"{s}_hand")
        fb = _body(model, f"{s}_forearm")
        if hb >= 0:
            kp[f"{s}_hand"] = (hb, np.zeros(3))
        elif fb >= 0:
            g = int(model.body_geomadr[fb])
            if g >= 0 and model.geom_type[g] == mujoco.mjtGeom.mjGEOM_CAPSULE:
                R = quat_to_mat(model.geom_quat[g])
                axis = R[:, 2] * model.geom_size[g, 1]
                ends = [model.geom_pos[g] + axis, model.geom_pos[g] - axis]
                kp[f"{s}_hand"] = (fb, max(ends, key=lambda e: -e[2]).copy())
    return {k: (int(b), np.asarray(o, float).copy()) for k, (b, o) in kp.items()}


def keypoint_positions(model: mujoco.MjModel, data: mujoco.MjData, keypoints: dict) -> np.ndarray:
    """World positions (K, 3) of keypoints after mj_kinematics."""
    return np.array([data.xpos[b] + data.xmat[b].reshape(3, 3) @ o for b, o in keypoints.values()])


# =========================================================================================================
# Motion
# =========================================================================================================
@dataclass
class Motion:
    fps: float
    root_pos: np.ndarray                 # (T, 3) world
    root_quat: np.ndarray                # (T, 4) wxyz, world
    joint_names: list[str]
    joint_pos: np.ndarray                # (T, J) radians (metres for slide joints)
    key_names: list[str] = field(default_factory=list)
    key_pos: np.ndarray | None = None    # (T, K, 3) world positions of key bodies
    loop: bool = False
    cycle: np.ndarray = field(default_factory=lambda: np.zeros(3))  # (dx, dy, dyaw): frame N = C(frame 0)
    name: str = ""
    meta: dict = field(default_factory=dict)

    def __post_init__(self):
        self.fps = float(self.fps)
        self.root_pos = np.asarray(self.root_pos, float).reshape(-1, 3)
        self.root_quat = quat_continuous(quat_normalize(np.asarray(self.root_quat, float).reshape(-1, 4)))
        self.joint_names = [str(n) for n in self.joint_names]
        self.joint_pos = np.asarray(self.joint_pos, float).reshape(len(self.root_pos), len(self.joint_names))
        self.key_names = [str(n) for n in self.key_names]
        if self.key_pos is not None:
            self.key_pos = np.asarray(self.key_pos, float).reshape(len(self.root_pos), len(self.key_names), 3)
        self.cycle = np.asarray(self.cycle, float).reshape(3)
        self.loop = bool(self.loop)
        if self.fps <= 0 or len(self.root_pos) < 1:
            raise ValueError("a motion needs fps > 0 and at least one frame")
        if not (np.isfinite(self.root_pos).all() and np.isfinite(self.joint_pos).all()):
            raise ValueError("motion contains non-finite values")

    # ---- basic properties -----------------------------------------------------------------------------
    @property
    def n_frames(self) -> int:
        return len(self.root_pos)

    @property
    def dt(self) -> float:
        return 1.0 / self.fps

    @property
    def duration(self) -> float:
        """Length in seconds: one period for a loop (N / fps), (N - 1) / fps otherwise."""
        n = self.n_frames
        return n / self.fps if self.loop else (n - 1) / self.fps

    @property
    def joints(self) -> dict[str, np.ndarray]:
        """Joint angle trajectories by name (views into joint_pos)."""
        return {n: self.joint_pos[:, i] for i, n in enumerate(self.joint_names)}

    def joint_index(self, name: str) -> int:
        return self.joint_names.index(name)

    def copy(self) -> "Motion":
        return Motion(self.fps, self.root_pos.copy(), self.root_quat.copy(), list(self.joint_names),
                      self.joint_pos.copy(), list(self.key_names),
                      None if self.key_pos is None else self.key_pos.copy(), self.loop, self.cycle.copy(),
                      self.name, json.loads(json.dumps(self.meta)))

    def summary(self) -> dict:
        return {"name": self.name, "frames": self.n_frames, "fps": round(self.fps, 4),
                "duration_s": round(self.duration, 4), "loop": self.loop, "joints": len(self.joint_names),
                "keys": list(self.key_names), "cycle": [round(float(v), 5) for v in self.cycle],
                "source": self.meta.get("source", "")}

    # ---- cycles -----------------------------------------------------------------------------------------
    def cycle_transform(self, c) -> np.ndarray:
        """Planar transform(s) (..., 3) of cycle index c (C^c; identity for c = 0 or non-looping motions).

        C maps x -> Rz(dyaw) (x - p0) + p0 + d with p0 = frame 0's root xy and d = (dx, dy); its c-th power
        is a rotation by c * dyaw plus a geometric sum of rotated displacements."""
        c = np.asarray(c, float)
        if not self.loop:
            return np.zeros(c.shape + (3,))
        dx, dy, dpsi = self.cycle
        p0 = self.root_pos[0, :2]
        psi = c * dpsi
        if abs(dpsi) < 1e-9:
            sx, sy = c * dx, c * dy
        else:  # sum_{j<c} Rz(j dpsi) d = Rz((c - 1) dpsi / 2) * sin(c dpsi / 2) / sin(dpsi / 2) * d
            k = np.sin(c * dpsi / 2) / np.sin(dpsi / 2)
            a = (c - 1) * dpsi / 2
            sx = k * (np.cos(a) * dx - np.sin(a) * dy)
            sy = k * (np.sin(a) * dx + np.cos(a) * dy)
        cs, sn = np.cos(psi), np.sin(psi)
        tx = p0[0] + sx - (cs * p0[0] - sn * p0[1])
        ty = p0[1] + sy - (sn * p0[0] + cs * p0[1])
        return np.stack([tx, ty, psi], axis=-1)

    def _index(self, k) -> tuple[np.ndarray, np.ndarray]:
        """Integer frame indices (any >= 0) -> (frame within the stored cycle, cycle number)."""
        k = np.asarray(k, np.int64)
        n = self.n_frames
        if self.loop:
            return np.mod(k, n), np.floor_divide(k, n)
        return np.clip(k, 0, n - 1), np.zeros_like(k)

    def frames(self, k) -> dict:
        """Frames at integer indices k (looping past the end with the cycle transform; clamped otherwise).
        -> {"root_pos", "root_quat", "joint_pos", "key_pos" (or None)} with a leading index axis."""
        i, c = self._index(k)
        T = self.cycle_transform(c)
        out = {"root_pos": planar_apply_points(T, self.root_pos[i]),
               "root_quat": planar_apply_quats(T, self.root_quat[i]),
               "joint_pos": self.joint_pos[i],
               "key_pos": None if self.key_pos is None else planar_apply_points(T, self.key_pos[i])}
        return out

    def sample(self, t) -> dict:
        """Interpolated frame(s) at time(s) t in seconds (same keys as `frames`). Loops repeat with the cycle
        transform; non-looping motions hold their first / last frame outside [0, duration]."""
        t = np.asarray(t, float)
        f = t * self.fps
        if not self.loop:
            f = np.clip(f, 0.0, self.n_frames - 1)
        i0 = np.floor(f).astype(np.int64)
        if not self.loop:
            i0 = np.minimum(i0, max(0, self.n_frames - 2))
        a = f - i0
        A, B = self.frames(i0), self.frames(i0 + 1)
        out = {"root_pos": A["root_pos"] + (B["root_pos"] - A["root_pos"]) * a[..., None],
               "root_quat": quat_slerp(A["root_quat"], B["root_quat"], a),
               "joint_pos": A["joint_pos"] + (B["joint_pos"] - A["joint_pos"]) * a[..., None],
               "key_pos": None}
        if A["key_pos"] is not None:
            out["key_pos"] = A["key_pos"] + (B["key_pos"] - A["key_pos"]) * a[..., None, None]
        return out

    # ---- derivatives ------------------------------------------------------------------------------------
    def velocities(self) -> dict:
        """Finite-difference velocities per stored frame (central; one-sided at the ends of non-looping
        motions): {"root_lin" (T, 3) world m/s, "root_ang" (T, 3) rad/s in the ROOT frame (MuJoCo's free-joint
        convention), "joint" (T, J), "key" (T, K, 3) or None}."""
        n, h = self.n_frames, 1.0 / self.fps
        k = np.arange(n)
        if self.loop:
            lo, hi = k - 1, k + 1
        else:
            lo, hi = np.maximum(k - 1, 0), np.minimum(k + 1, n - 1)
        if n == 1:
            lo = hi = k
        span = np.maximum(hi - lo, 1) * h
        A, B = self.frames(lo), self.frames(hi)   # a loop's frame -1 / N come from the previous / next cycle
        lin = (B["root_pos"] - A["root_pos"]) / span[:, None]
        joint = (B["joint_pos"] - A["joint_pos"]) / span[:, None]
        # angular velocity in the root frame of frame k: q_k^-1 (q_hi q_lo^-1) q_k, as a rotation vector
        dq = quat_mul(B["root_quat"], quat_conj(A["root_quat"]))            # world-frame rotation lo -> hi
        w_world = quat_to_rotvec(dq) / span[:, None]
        R = quat_to_mat(self.root_quat)
        ang = np.einsum("nji,nj->ni", R, w_world)
        key = None
        if self.key_pos is not None:
            key = (B["key_pos"] - A["key_pos"]) / span[:, None, None]
        return {"root_lin": lin, "root_ang": ang, "joint": joint, "key": key}

    # ---- model mapping ------------------------------------------------------------------------------------
    def joint_qpos_map(self, model: mujoco.MjModel) -> tuple[np.ndarray, np.ndarray]:
        """(motion column indices, model qpos addresses) of the joints both share."""
        cols, adr = [], []
        for i, n in enumerate(self.joint_names):
            j = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, n)
            if j >= 0 and model.jnt_type[j] in (mujoco.mjtJoint.mjJNT_HINGE, mujoco.mjtJoint.mjJNT_SLIDE):
                cols.append(i)
                adr.append(int(model.jnt_qposadr[j]))
        return np.array(cols, int), np.array(adr, int)

    def qpos(self, model: mujoco.MjModel, k=None, frames: dict | None = None) -> np.ndarray:
        """Model qpos (n, nq) for frame indices k (default: all stored frames). Joints the motion lacks keep
        model.qpos0; free bodies other than the root (props) keep their qpos0 too."""
        fr = frames if frames is not None else self.frames(np.arange(self.n_frames) if k is None else k)
        n = len(fr["root_pos"])
        _, qa, _ = free_root(model)
        q = np.tile(model.qpos0, (n, 1))
        q[:, qa:qa + 3] = fr["root_pos"]
        q[:, qa + 3:qa + 7] = fr["root_quat"]
        cols, adr = self.joint_qpos_map(model)
        q[:, adr] = fr["joint_pos"][:, cols]
        return q

    def qvel(self, model: mujoco.MjModel) -> np.ndarray:
        """Model qvel (T, nv) of every stored frame from the finite-difference velocities."""
        v = self.velocities()
        _, _, da = free_root(model)
        out = np.zeros((self.n_frames, model.nv))
        out[:, da:da + 3] = v["root_lin"]
        out[:, da + 3:da + 6] = v["root_ang"]
        for i, n in enumerate(self.joint_names):
            j = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, n)
            if j >= 0 and model.jnt_type[j] in (mujoco.mjtJoint.mjJNT_HINGE, mujoco.mjtJoint.mjJNT_SLIDE):
                out[:, model.jnt_dofadr[j]] = v["joint"][:, i]
        return out

    def with_keypoints(self, model: mujoco.MjModel, names: list[str] | None = None) -> "Motion":
        """Copy with key_pos filled by forward kinematics of `model` (robot_keypoints; all by default)."""
        kp = robot_keypoints(model)
        names = list(kp) if names is None else [n for n in names if n in kp]
        sel = {n: kp[n] for n in names}
        d = mujoco.MjData(model)
        qs = self.qpos(model)
        keys = np.zeros((self.n_frames, len(sel), 3))
        for t in range(self.n_frames):
            d.qpos[:] = qs[t]
            mujoco.mj_kinematics(model, d)
            keys[t] = keypoint_positions(model, d, sel)
        m = self.copy()
        m.key_names, m.key_pos = names, keys
        return m

    @classmethod
    def from_qpos(cls, model: mujoco.MjModel, qpos: np.ndarray, fps: float, name: str = "", loop: bool = False,
                  cycle=None, keypoints: bool | list[str] = True, meta: dict | None = None) -> "Motion":
        """Motion from a model qpos trajectory (T, nq): root + every hinge/slide joint (+ key bodies)."""
        qpos = np.atleast_2d(np.asarray(qpos, float))
        _, qa, _ = free_root(model)
        names = one_dof_joints(model)
        adr = [int(model.jnt_qposadr[model.joint(n).id]) for n in names]
        m = cls(fps, qpos[:, qa:qa + 3], qpos[:, qa + 3:qa + 7], names, qpos[:, adr], loop=loop,
                cycle=np.zeros(3) if cycle is None else cycle, name=name, meta=dict(meta or {}))
        if keypoints:
            m = m.with_keypoints(model, None if keypoints is True else list(keypoints))
        return m

    @classmethod
    def from_cycle(cls, model: mujoco.MjModel, qpos: np.ndarray, fps: float, name: str = "",
                   meta: dict | None = None, keypoints: bool | list[str] = True,
                   stationary: bool = False) -> "Motion":
        """Looping motion from N + 1 qpos frames where the last one is one period after the first.

        The cycle transform C is the planar motion of the root's heading frame over the period. What C does
        not explain (joint angles, root height, pitch and roll that differ between the two ends) is removed
        with a linear ramp over the cycle, so the loop closes exactly; the last frame is then dropped.
        stationary=True forces C = identity (in-place motions: any small drift is ramped out instead)."""
        qpos = np.asarray(qpos, float)
        if len(qpos) < 3:
            raise ValueError("a cycle needs at least 3 frames")
        _, qa, _ = free_root(model)
        n = len(qpos) - 1
        h0 = heading_pose(qpos[0, qa:qa + 3], qpos[0, qa + 3:qa + 7])
        hn = heading_pose(qpos[n, qa:qa + 3], qpos[n, qa + 3:qa + 7])
        dyaw = float(wrap_angle(hn[2] - h0[2]))
        # C(x) = Rz(dyaw)(x - p0) + p0 + d  with  C(p0) = pN  ->  d = pN - p0
        d = hn[:2] - h0[:2]
        if stationary:   # an in-place motion (gesture, squat): the loop must not drift, ramp out everything
            d, dyaw = np.zeros(2), 0.0
        T = planar_between(h0, np.array([h0[0] + d[0], h0[1] + d[1], h0[2] + dyaw]))
        pred_pos = planar_apply_points(T, qpos[0, qa:qa + 3])
        pred_quat = planar_apply_quats(T, qpos[0, qa + 3:qa + 7])
        ramp = (np.arange(n + 1) / n)[:, None]
        q = qpos.copy()
        q[:, qa + 3:qa + 7] = quat_continuous(quat_normalize(q[:, qa + 3:qa + 7]))
        # root position residual (height, and xy beyond the heading-frame motion)
        q[:, qa:qa + 3] -= ramp * (qpos[n, qa:qa + 3] - pred_pos)
        # root orientation residual: rotate by a fraction of the end mismatch
        err = quat_to_rotvec(quat_mul(pred_quat, quat_conj(qpos[n, qa + 3:qa + 7])))
        q[:, qa + 3:qa + 7] = quat_mul(rotvec_to_quat(ramp * err), q[:, qa + 3:qa + 7])
        names = one_dof_joints(model)
        adr = np.array([int(model.jnt_qposadr[model.joint(nm).id]) for nm in names], int)
        q[:, adr] -= ramp * (qpos[n, adr] - qpos[0, adr])
        return cls.from_qpos(model, q[:n], fps, name=name, loop=True, cycle=[d[0], d[1], dyaw],
                             keypoints=keypoints, meta=meta)

    # ---- editing -------------------------------------------------------------------------------------------
    def resample(self, fps: float) -> "Motion":
        """Same motion at another frame rate. A loop keeps its period exactly (round(N fps / fps_old) frames,
        fps adjusted by < 0.5 frame per period); a clip keeps its first and last frames."""
        fps = float(fps)
        if abs(fps - self.fps) < 1e-9:
            return self.copy()
        if self.loop:
            n = max(2, int(round(self.n_frames * fps / self.fps)))
            new_fps = n / self.duration
            t = np.arange(n) / new_fps
        else:
            n = max(1, int(round(self.duration * fps)) + 1)
            new_fps = fps if n > 1 else self.fps
            t = np.minimum(np.arange(n) / fps, self.duration)
        fr = self.sample(t)
        return Motion(new_fps, fr["root_pos"], fr["root_quat"], list(self.joint_names), fr["joint_pos"],
                      list(self.key_names), fr["key_pos"], self.loop, self.cycle.copy(), self.name,
                      json.loads(json.dumps(self.meta)))

    def transformed(self, T) -> "Motion":
        """Copy moved by a planar transform (tx, ty, yaw) applied to the whole motion."""
        T = np.asarray(T, float).reshape(3)
        m = self.copy()
        m.root_pos = planar_apply_points(T, self.root_pos)
        m.root_quat = planar_apply_quats(T, self.root_quat)
        if self.key_pos is not None:
            m.key_pos = planar_apply_points(T, self.key_pos)
        # the cycle displacement is a vector in the world frame: rotate it with the motion
        d = planar_apply_vectors(T, np.array([self.cycle[0], self.cycle[1], 0.0]))
        m.cycle = np.array([d[0], d[1], self.cycle[2]])
        return m

    def aligned(self, x: float = 0.0, y: float = 0.0, yaw: float = 0.0) -> "Motion":
        """Copy whose first frame's heading frame (root xy + yaw) is (x, y, yaw)."""
        h0 = heading_pose(self.root_pos[0], self.root_quat[0])
        return self.transformed(planar_between(h0, np.array([x, y, yaw], float)))

    # ---- files ------------------------------------------------------------------------------------------
    def to_arrays(self, prefix: str = "") -> dict[str, np.ndarray]:
        out = {f"{prefix}fps": np.array(self.fps), f"{prefix}root_pos": self.root_pos.astype(np.float32),
               f"{prefix}root_quat": self.root_quat.astype(np.float32),
               f"{prefix}joint_pos": self.joint_pos.astype(np.float32), f"{prefix}cycle": self.cycle.copy()}
        if self.key_pos is not None:
            out[f"{prefix}key_pos"] = self.key_pos.astype(np.float32)
        return out

    def header(self) -> dict:
        return {"format": MOTION_FORMAT, "version": 1, "name": self.name, "loop": self.loop,
                "joint_names": self.joint_names, "key_names": self.key_names, "meta": self.meta}

    @classmethod
    def from_arrays(cls, arrays, header: dict, prefix: str = "") -> "Motion":
        if header.get("format") != MOTION_FORMAT:
            raise ValueError(f"not a Simulatics motion (format {header.get('format')!r})")
        kp = arrays.get(f"{prefix}key_pos")
        return cls(float(arrays[f"{prefix}fps"]), np.asarray(arrays[f"{prefix}root_pos"], float),
                   np.asarray(arrays[f"{prefix}root_quat"], float), header["joint_names"],
                   np.asarray(arrays[f"{prefix}joint_pos"], float), header.get("key_names", []),
                   None if kp is None else np.asarray(kp, float), bool(header.get("loop", False)),
                   np.asarray(arrays.get(f"{prefix}cycle", np.zeros(3)), float), header.get("name", ""),
                   header.get("meta", {}))

    def save(self, path: str | Path) -> Path:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.stem + ".tmp.npz")
        np.savez_compressed(tmp, header=np.array(json.dumps(self.header())), **self.to_arrays())
        tmp.replace(path)
        return path

    @classmethod
    def load(cls, path: str | Path) -> "Motion":
        with np.load(path, allow_pickle=False) as z:
            arrays = {k: z[k] for k in z.files if k != "header"}
            header = json.loads(str(z["header"])) if "header" in z.files else {}
        m = cls.from_arrays(arrays, header)
        if not m.name:
            m.name = Path(path).stem
        return m


def is_motion_file(path: str | Path) -> bool:
    try:
        with np.load(path, allow_pickle=False) as z:
            return "header" in z.files and json.loads(str(z["header"])).get("format") == MOTION_FORMAT
    except Exception:
        return False
